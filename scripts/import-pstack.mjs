#!/usr/bin/env node
// Verbatim importer: copies the listed pstack files from a cursor/plugins checkout into core/.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const CC = 'harness/pstack/claude-code';

export function importPstack({ src, out, list }) {
  const head = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD']).toString().trim();
  if (!head.startsWith(list.commit)) throw new Error(`checkout is at ${head}, expected ${list.commit}`);

  const copied = [];
  const cp = (from, to) => {
    fs.mkdirSync(path.dirname(path.join(out, to)), { recursive: true });
    fs.cpSync(path.join(src, from), path.join(out, to), { recursive: true });
    copied.push(to);
  };
  const base = (rel) => path.join(CC, rel);

  for (const s of list.skills) {
    if (s !== 'poteto-mode') { cp(base(`skills/${s}`), `skills/${s}`); continue; }
    const dir = base('skills/poteto-mode');
    for (const e of fs.readdirSync(path.join(src, dir)))
      if (e !== 'playbooks') cp(path.join(dir, e), `skills/poteto-mode/${e}`);
    for (const p of list.modePlaybooks)
      cp(path.join(dir, `playbooks/${p}.md`), `skills/poteto-mode/playbooks/${p}.md`);
  }
  for (const a of list.agents) cp(base(`agents/${a}.md`), `agents/${a}.md`);
  for (const { from, to } of list.extra) cp(from, to);

  fs.cpSync(path.join(src, base('LICENSE')), path.join(out, 'LICENSE-pstack'));
  fs.writeFileSync(
    path.join(out, 'UPSTREAM.md'),
    `# Upstream\n\nVerbatim import of pstack from https://github.com/cursor/plugins at commit ${head} (${list.commit}).\nGenerated by scripts/import-pstack.mjs; do not edit by hand.\n\n## Copied\n\n${copied.map((c) => `- ${c}`).join('\n')}\n`,
  );
  return { copied };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const arg = (n) => process.argv[process.argv.indexOf(n) + 1];
  const list = JSON.parse(fs.readFileSync(new URL('./import-list.json', import.meta.url), 'utf8'));
  const { copied } = importPstack({ src: arg('--src'), out: arg('--out'), list });
  console.log(`copied ${copied.length} entries`);
}
